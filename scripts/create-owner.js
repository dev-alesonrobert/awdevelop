import 'dotenv/config';
import readline from 'node:readline/promises';
import { Writable } from 'node:stream';
import { createAuth } from '../server/auth.js';
import { getPool } from '../server/db.js';
if (!process.stdin.isTTY) throw new Error('Execute em um terminal interativo para definir sua senha.');
if (!process.env.ADMIN_EMAIL) throw new Error('Configure ADMIN_EMAIL primeiro.');
const existing = await getPool().query('SELECT id FROM "user" WHERE email=$1', [process.env.ADMIN_EMAIL.toLowerCase()]);
if (existing.rowCount) throw new Error('A conta já existe. Nenhuma senha foi alterada.');
let muted = false;
const output = new Writable({ write(chunk, encoding, callback) { if (!muted) process.stdout.write(chunk, encoding); callback(); } });
const rl = readline.createInterface({ input:process.stdin, output, terminal:true });
process.stdout.write('Senha administrativa (mínimo 12 caracteres): '); muted=true;
const password = await rl.question('');
muted=false; process.stdout.write('\nConfirme a senha: '); muted=true;
const confirmation = await rl.question(''); rl.close(); process.stdout.write('\n');
if (password !== confirmation || password.length < 12) throw new Error('As senhas precisam coincidir e ter ao menos 12 caracteres.');
await createAuth({ provisioning:true }).api.signUpEmail({ body:{ name:'Aleson Roberto', email:process.env.ADMIN_EMAIL.toLowerCase(), password } });
await getPool().end();
console.log('Conta administrativa criada. O cadastro público permanece fechado.');
